"""
Caregiver web-push (RFC 8030) delivery for emergency events.

Not to be confused with the in-app browser `Notification` API: these pushes
are real Web Push delivered by a service worker through a push service
(FCM/Mozilla/Apple), so they work while the caretaker app is closed — subject
to internet availability and the user having granted permission.

Explicit non-guarantee (documented for the demo): pushing happens over the
internet. If the Pi is offline, deliveries stay 'queued' locally and are sent
when connectivity returns (the sync worker owns the send loop). If the
browser hasn't granted permission or the page isn't installed as a PWA, the
delivery is 'failed'/'accepted' semantics are reported honestly — a delivery
is only marked 'accepted' after the push service returns 201.

VAPID keys live in the server env (never in frontend bundles or firmware):
  VAPID_PUBLIC_KEY / VAPID_PRIVATE_KEY  (urlsafe-base64 DER, as generated by
  `python -m backend.push_service`), optional PUSH_SUBJECT (mailto:).
"""
import json
import os
import sqlite3
import time
from typing import Any, Callable, Dict, List, Optional

from backend.db import get_conn

VAPID_SUBJECT_DEFAULT = "mailto:safebath@localhost"
MAX_PUSH_ATTEMPTS = 5
PUSH_BACKOFF_BASE = 2.0
PUSH_BACKOFF_CAP = 600.0


def get_db_path() -> str:
    return os.environ.get("SQLITE_PATH", "data/events.db")


def load_keys() -> Dict[str, str]:
    """Read VAPID keys from env. Missing keys are reported loudly (returns
    empty dict) so callers/tests can skip real sending without a crash."""
    pub = os.environ.get("VAPID_PUBLIC_KEY", "").strip()
    priv = os.environ.get("VAPID_PRIVATE_KEY", "").strip()
    if not pub and not priv:
        return {}
    if not pub or not priv:
        raise RuntimeError(
            "VAPID_PUBLIC_KEY and VAPID_PRIVATE_KEY must be set together")
    return {"public_key": pub, "private_key": priv}


def generate_keys_and_print() -> None:
    """Generate a VAPID keypair and print the two env lines to set on the Pi."""
    try:
        from py_vapid import b64urlencode, generate_vapid_keys
    except Exception as e:  # pragma: no cover - only run by an operator
        raise SystemExit(f"py-vapid not installed: {e}") from e
    keys = generate_vapid_keys()
    print("Add these to /etc/safebath/safebath.env (0600):")
    print(f"VAPID_PUBLIC_KEY={b64urlencode(keys.public_key.public_bytes(64, 0x04)[1:])}")
    print(f"VAPID_PRIVATE_KEY={b64urlencode(keys.private_key.private_bytes(64, 0x04)[:32])}")
    print("Or, with a fresh venv: VAPID_PRIVATE_KEY / VAPID_PUBLIC_KEY")
    print("PUSH_SUBJECT=mailto:you@example.com")


# --------------------------------------------------------------------------- #
# Subscription store
# --------------------------------------------------------------------------- #
def subscribe(db_path: str, endpoint: str, p256dh: str, auth: str,
              now: Optional[float] = None) -> int:
    if not endpoint or not p256dh or not auth:
        raise ValueError("endpoint, p256dh and auth are required")
    now = now if now is not None else time.time()
    conn = get_conn(db_path)
    try:
        conn.execute(
            "INSERT INTO push_subscriptions(endpoint, p256dh, auth, "
            " created_at, last_seen, enabled) "
            "VALUES (?,?,?,?,?,1) "
            "ON CONFLICT(endpoint) DO UPDATE SET "
            " p256dh=excluded.p256dh, auth=excluded.auth, "
            " last_seen=excluded.last_seen, enabled=1",
            (endpoint, p256dh, auth, now, now))
        conn.commit()
        row = conn.execute("SELECT id FROM push_subscriptions WHERE endpoint=?",
                           (endpoint,)).fetchone()
        return row["id"]
    finally:
        conn.close()


def unsubscribe(db_path: str, endpoint: str) -> None:
    conn = get_conn(db_path)
    try:
        conn.execute("UPDATE push_subscriptions SET enabled=0 WHERE endpoint=?",
                     (endpoint,))
        conn.commit()
    finally:
        conn.close()


def count_subscriptions(db_path: str) -> int:
    conn = get_conn(db_path)
    try:
        return conn.execute(
            "SELECT COUNT(*) FROM push_subscriptions WHERE enabled=1"
        ).fetchone()[0]
    finally:
        conn.close()


def _sub_rows(db_path: str, only_enabled: bool = True) -> List[sqlite3.Row]:
    conn = get_conn(db_path)
    try:
        where = "WHERE enabled=1" if only_enabled else ""
        return conn.execute(
            f"SELECT id, endpoint, p256dh, auth FROM push_subscriptions "
            f"{where}").fetchall()
    finally:
        conn.close()


# --------------------------------------------------------------------------- #
# Delivery state machine (run by the sync worker; offline-safe)
# --------------------------------------------------------------------------- #
def queue_due_deliveries(db_path: str, now: Optional[float] = None,
                         limit: int = 50) -> List[sqlite3.Row]:
    now = now if now is not None else time.time()
    conn = get_conn(db_path)
    try:
        return conn.execute(
            "SELECT d.id, d.event_id, d.subscription_id, d.status, d.attempts, "
            "       s.endpoint, s.p256dh, s.auth "
            "FROM notification_deliveries d "
            "JOIN push_subscriptions s ON s.id=d.subscription_id "
            "WHERE d.status IN ('queued','failed','attempted') "
            "  AND d.next_attempt_at IS NOT NULL AND d.next_attempt_at <= ? "
            "ORDER BY d.next_attempt_at LIMIT ?",
            (now, limit)).fetchall()
    finally:
        conn.close()


def _delivery_backoff(attempts: int) -> float:
    import random
    delay = min(PUSH_BACKOFF_BASE ** attempts, PUSH_BACKOFF_CAP)
    return delay * (1.0 + random.uniform(-0.2, 0.2))


def update_delivery(db_path: str, delivery_id: int, status: str,
                    error: Optional[str] = None,
                    now: Optional[float] = None) -> None:
    now = now if now is not None else time.time()
    conn = get_conn(db_path)
    try:
        if status == "accepted":
            conn.execute(
                "UPDATE notification_deliveries SET status='accepted', "
                "last_error=NULL, sent_at=?, next_attempt_at=NULL "
                "WHERE id=?", (now, delivery_id))
        elif status == "failed_permanent":
            conn.execute(
                "UPDATE notification_deliveries SET status='failed', "
                "last_error=?, next_attempt_at=NULL WHERE id=?",
                (error[:300], delivery_id))
        else:  # queued (retry later)
            row = conn.execute(
                "SELECT attempts FROM notification_deliveries WHERE id=?",
                (delivery_id,)).fetchone()
            attempts = (row["attempts"] + 1) if row else 1
            if attempts >= MAX_PUSH_ATTEMPTS:
                conn.execute(
                    "UPDATE notification_deliveries SET status='failed', "
                    "attempts=?, last_error=?, next_attempt_at=NULL "
                    "WHERE id=?", (attempts, error[:300], delivery_id))
            else:
                conn.execute(
                    "UPDATE notification_deliveries SET status='queued', "
                    "attempts=?, last_error=?, next_attempt_at=? "
                    "WHERE id=?", (attempts, error[:300],
                                   now + _delivery_backoff(attempts),
                                   delivery_id))
        conn.commit()
    finally:
        conn.close()


def send_one(db_path: str, row: sqlite3.Row,
             payload: Dict[str, Any],
             send_fn: Optional[Callable] = None,
             now: Optional[float] = None) -> str:
    """
    Attempt a single push. Returns the resulting delivery status
    ('accepted' | 'queued' | 'failed' | 'subscription_disabled').
    `send_fn` is injectable for tests (defaults to pywebpush).
    """
    now = now if now is not None else time.time()
    sub = {"endpoint": row["endpoint"],
           "keys": {"p256dh": row["p256dh"], "auth": row["auth"]}}
    keys = load_keys()
    if not keys:
        update_delivery(db_path, row["id"], "queued",
                        error="VAPID keys not configured on server",
                        now=now)
        return "queued"

    if send_fn is None:
        try:
            from pywebpush import webpush
        except ImportError:
            update_delivery(db_path, row["id"], "queued",
                            error="pywebpush not installed", now=now)
            return "queued"
    else:
        webpush = send_fn

    claims = {"sub": os.environ.get("PUSH_SUBJECT", VAPID_SUBJECT_DEFAULT)}
    try:
        if send_fn is None:
            webpush(subscription_info=sub,
                    data=json.dumps(payload),
                    vapid_private_key=keys["private_key"],
                    vapid_claims=claims,
                    timeout=10)
        else:
            webpush(sub, payload, keys, claims)
        update_delivery(db_path, row["id"], "accepted", now=now)
        return "accepted"
    except Exception as e:
        err = str(e)
        # push services return 404/410 when the subscription is gone
        if "404" in err or "410" in err or "gone" in err.lower():
            conn = get_conn(db_path)
            try:
                conn.execute("UPDATE push_subscriptions SET enabled=0 "
                             "WHERE id=?", (row["subscription_id"],))
                conn.commit()
            finally:
                conn.close()
            update_delivery(db_path, row["id"], "failed_permanent",
                            error=f"subscription gone: {err}", now=now)
            return "subscription_disabled"
        update_delivery(db_path, row["id"], "queued", error=err, now=now)
        return "queued"


def delivery_summary(db_path: str) -> Dict[str, int]:
    conn = get_conn(db_path)
    try:
        rows = conn.execute(
            "SELECT status, COUNT(*) AS n FROM notification_deliveries "
            "GROUP BY status").fetchall()
        out = {"queued": 0, "attempted": 0, "accepted": 0,
               "failed": 0, "acknowledged": 0}
        for r in rows:
            out[r["status"]] = r["n"]
        return out
    finally:
        conn.close()


def mark_delivery_acknowledged(db_path: str, event_id: str) -> None:
    conn = get_conn(db_path)
    try:
        conn.execute(
            "UPDATE notification_deliveries SET status='acknowledged', "
            "acknowledged_at=? "
            "WHERE event_id=? AND status IN ('accepted','attempted','queued')",
            (time.time(), event_id))
        conn.commit()
    finally:
        conn.close()


# --------------------------------------------------------------------------- #
# Payload builder
# --------------------------------------------------------------------------- #
def build_payload(event: Dict) -> Dict[str, Any]:
    return {
        "title": "SafeBath emergency",
        "body": event.get("message", "Safety alert"),
        "tag": f"safebath-emg-{event.get('event_id', '')}",
        "data": {
            "event_id": event.get("event_id", ""),
            "url": "/caretaker.html",
        },
    }


