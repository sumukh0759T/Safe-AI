"""
Converts every models/*.h5 into a quantized .tflite and generates the C header
arrays that firmware/shared/model_data/ expects, reporting estimated tensor
arena size (ESP32 constraint: < 100KB per SOFTWARE_BUILD_SPEC Section 5.1).

Usage:  python training/convert_to_tflite.py [model1.h5 model2.h5 ...]
        (no args -> converts all *.h5 in models/)

Conversion strategy (TF 2.16): builtin-op-only conversion first; recurrent
layers (ConvLSTM/LSTM) whose while-loops cannot be legalized fall back to
SELECT_TF_OPS. Flex-flagged outputs run fine in the laptop tf.lite runtime /
API server but are NOT TFLite-Micro compatible — restructure those models into
static graphs before embedding them on the ESP32.
"""
import glob
import os
import sys

# TF 2.16 + Keras 3 cannot lower recurrent layers to TFLite (LLVM abort);
# tf_keras (Keras 2) serializes them into a convertible graph. Must be set
# before the first tensorflow import in this process.
os.environ.setdefault("TF_USE_LEGACY_KERAS", "1")


def c_array(name, data: bytes) -> str:
    lines = [f"// auto-generated by training/convert_to_tflite.py — do not edit"]
    lines.append(f"#pragma once")
    lines.append(f"#include <pgmspace.h>")
    lines.append(f"const unsigned int {name}_len = {len(data)};")
    lines.append(f"const unsigned char {name}[] PROGMEM = {{")
    for i in range(0, len(data), 12):
        chunk = ", ".join(f"0x{b:02x}" for b in data[i:i + 12])
        lines.append(f"  {chunk},")
    lines.append("};")
    return "\n".join(lines)


def convert(h5_path: str) -> str:
    import tensorflow as tf
    model = tf.keras.models.load_model(h5_path)

    def make_converter():
        c = tf.lite.TFLiteConverter.from_keras_model(model)
        c.optimizations = [tf.lite.Optimize.DEFAULT]   # dynamic-range int8
        return c

    flex_note = ""
    try:
        converter = make_converter()
        converter.experimental_enable_resource_variables = True
        tflite = converter.convert()
    except Exception:
        converter = make_converter()
        converter.target_spec.supported_ops = [
            tf.lite.OpsSet.TFLITE_BUILTINS, tf.lite.OpsSet.SELECT_TF_OPS]
        converter._experimental_lower_tensor_list_ops = False
        converter.experimental_enable_resource_variables = True
        tflite = converter.convert()
        flex_note = " [FLEX ops present — laptop/eval only, NOT ESP32/TFLite-Micro compatible]"

    out = h5_path.replace(".h5", ".tflite")
    with open(out, "wb") as f:
        f.write(tflite)

    # estimate arena requirement from tensor allocation details
    interp = tf.lite.Interpreter(model_path=out)
    interp.allocate_tensors()
    used = sum(t.get("bytes", 0) for t in interp.get_tensor_details())
    print(f"{out}: {len(tflite)/1024:.1f} KB file; "
          f"tensor details sum ~{used/1024:.1f} KB "
          f"({'OK <100KB' if used < 100 * 1024 else 'CHECK — near/over ESP32 budget'})"
          f"{flex_note}")

    # emit firmware header
    base = os.path.splitext(os.path.basename(out))[0]
    var = "".join(p.capitalize() or "_" for p in base.split("_"))
    hdr = c_array(var + "_model_data", tflite)
    os.makedirs("firmware/shared/model_data", exist_ok=True)
    hdr_path = os.path.join("firmware", "shared", "model_data",
                            base + "_model_data.h")
    with open(hdr_path, "w") as f:
        f.write(hdr)
    print(f"  header written: {hdr_path}")
    return out


def main():
    try:
        import tensorflow as tf  # noqa: F401
    except ImportError:
        raise SystemExit("tensorflow not installed — pip install tensorflow")
    targets = sys.argv[1:] or sorted(glob.glob(os.path.join("models", "*.h5")))
    if not targets:
        print("no .h5 models found in models/ — train something first")
        return
    for t in targets:
        try:
            convert(t)
        except Exception as e:
            print(f"FAILED {t}: {e}")


if __name__ == "__main__":
    main()
